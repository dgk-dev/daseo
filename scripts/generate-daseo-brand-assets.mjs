import { createHash } from "node:crypto";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import sharp from "sharp";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_RELATIVE_PATH = "packages/app/assets/brand/daseo-mark.svg";
const GENERATED_MODULE_PATH = "packages/app/src/components/icons/daseo-logo-path.generated.ts";
const MANIFEST_PATH = "packages/app/assets/brand/generated-assets.json";

const BRAND = Object.freeze({
  viewBox: "0 0 512 512",
  background: "#0A0A0C",
  foreground: "#F0F0F2",
  notificationForeground: "#FFFFFF",
  running: "#3B82F6",
  attention: "#22C55E",
  fullMarkScale: 0.84,
  adaptiveMarkScale: 0.57,
  splashMarkScale: 0.54,
  notificationMarkScale: 0.96,
  tileMarkScale: 0.68,
});

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function escapeXmlAttribute(value) {
  return value.replaceAll("&", "&amp;").replaceAll('"', "&quot;");
}

function readCanonicalMark(source) {
  const viewBox = /\bviewBox="([^"]+)"/.exec(source)?.[1];
  const pathMatch = /<path\b[^>]*\bid="daseo-mark"[^>]*\bd="([^"]+)"[^>]*\/?\s*>/.exec(source);
  if (viewBox !== BRAND.viewBox) {
    throw new Error(`Expected Daseo viewBox ${BRAND.viewBox}, received ${String(viewBox)}`);
  }
  if (!pathMatch?.[1]) {
    throw new Error(`Missing #daseo-mark path in ${SOURCE_RELATIVE_PATH}`);
  }
  return { pathData: pathMatch[1], viewBox };
}

function markTransform(scale) {
  return `translate(256 256) scale(${scale}) translate(-256 -256)`;
}

function createBrandSvg({
  pathData,
  background = null,
  foreground = BRAND.foreground,
  markScale,
  tile = false,
  statusColor = null,
  pixelSize = null,
}) {
  const dimensions = pixelSize ? ` width="${pixelSize}" height="${pixelSize}"` : "";
  let backgroundNode = "";
  if (tile) {
    backgroundNode = `<rect x="47" y="47" width="418" height="418" rx="96" fill="${BRAND.background}"/>`;
  } else if (background) {
    backgroundNode = `<rect width="512" height="512" fill="${background}"/>`;
  }
  const statusNode = statusColor ? `<circle cx="390" cy="390" r="90" fill="${statusColor}"/>` : "";
  return [
    `<svg xmlns="http://www.w3.org/2000/svg"${dimensions} viewBox="${BRAND.viewBox}">`,
    backgroundNode,
    `<path transform="${markTransform(markScale)}" d="${escapeXmlAttribute(pathData)}" fill="${foreground}" fill-rule="evenodd" clip-rule="evenodd"/>`,
    statusNode,
    "</svg>",
    "",
  ].join("\n");
}

async function renderPng(svg, size) {
  return sharp(Buffer.from(svg))
    .resize(size, size, { fit: "fill" })
    .png({ compressionLevel: 9, adaptiveFiltering: false, palette: false })
    .toBuffer();
}

function createIco(images) {
  const count = images.length;
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(count, 4);
  const directory = Buffer.alloc(16 * count);
  let offset = header.length + directory.length;
  images.forEach(({ size, data }, index) => {
    const entryOffset = index * 16;
    directory.writeUInt8(size === 256 ? 0 : size, entryOffset);
    directory.writeUInt8(size === 256 ? 0 : size, entryOffset + 1);
    directory.writeUInt8(0, entryOffset + 2);
    directory.writeUInt8(0, entryOffset + 3);
    directory.writeUInt16LE(1, entryOffset + 4);
    directory.writeUInt16LE(32, entryOffset + 6);
    directory.writeUInt32LE(data.length, entryOffset + 8);
    directory.writeUInt32LE(offset, entryOffset + 12);
    offset += data.length;
  });
  return Buffer.concat([header, directory, ...images.map(({ data }) => data)]);
}

function createIcns(imagesBySize) {
  const chunks = [
    ["icp4", 16],
    ["icp5", 32],
    ["icp6", 64],
    ["ic07", 128],
    ["ic08", 256],
    ["ic09", 512],
    ["ic10", 1024],
    ["ic11", 32],
    ["ic12", 64],
    ["ic13", 256],
    ["ic14", 512],
  ].map(([type, size]) => {
    const data = imagesBySize.get(size);
    if (!data) throw new Error(`Missing ${size}px ICNS source`);
    const header = Buffer.alloc(8);
    header.write(type, 0, 4, "ascii");
    header.writeUInt32BE(data.length + 8, 4);
    return Buffer.concat([header, data]);
  });
  const body = Buffer.concat(chunks);
  const header = Buffer.alloc(8);
  header.write("icns", 0, 4, "ascii");
  header.writeUInt32BE(body.length + 8, 4);
  return Buffer.concat([header, body]);
}

function createGeneratedModule({ pathData, viewBox }) {
  return `/** Generated by scripts/generate-daseo-brand-assets.mjs. Do not edit. */\nexport const DASEO_LOGO_VIEW_BOX = "${viewBox}";\nexport const DASEO_LOGO_PATH =\n  "${pathData}";\n`;
}

async function addRasterOutput(outputs, relativePath, svg, size) {
  outputs.set(relativePath, await renderPng(svg, size));
}

export async function buildBrandOutputs() {
  const sourcePath = path.join(REPO_ROOT, SOURCE_RELATIVE_PATH);
  const source = await readFile(sourcePath, "utf8");
  const mark = readCanonicalMark(source);
  const outputs = new Map();
  outputs.set(GENERATED_MODULE_PATH, createGeneratedModule(mark));

  const fullSvg = createBrandSvg({
    pathData: mark.pathData,
    background: BRAND.background,
    markScale: BRAND.fullMarkScale,
  });
  const adaptiveSvg = createBrandSvg({
    pathData: mark.pathData,
    markScale: BRAND.adaptiveMarkScale,
  });
  const splashSvg = createBrandSvg({
    pathData: mark.pathData,
    markScale: BRAND.splashMarkScale,
  });
  const notificationSvg = createBrandSvg({
    pathData: mark.pathData,
    foreground: BRAND.notificationForeground,
    markScale: BRAND.notificationMarkScale,
  });
  const tileSvg = createBrandSvg({
    pathData: mark.pathData,
    markScale: BRAND.tileMarkScale,
    tile: true,
  });

  await addRasterOutput(outputs, "packages/app/assets/images/icon.png", fullSvg, 1024);
  await addRasterOutput(
    outputs,
    "packages/app/assets/images/android-icon-foreground.png",
    adaptiveSvg,
    1024,
  );
  await addRasterOutput(outputs, "packages/app/assets/images/favicon.png", fullSvg, 48);
  await addRasterOutput(outputs, "packages/app/assets/images/splash-icon.png", splashSvg, 200);
  await addRasterOutput(
    outputs,
    "packages/app/assets/images/notification-icon.png",
    notificationSvg,
    96,
  );
  await addRasterOutput(outputs, "packages/app/public/apple-touch-icon.png", fullSvg, 180);
  await addRasterOutput(outputs, "packages/app/public/pwa-icon-192.png", fullSvg, 192);
  await addRasterOutput(outputs, "packages/app/public/pwa-icon-512.png", fullSvg, 512);

  const faviconVariants = [
    ["", null],
    ["-running", BRAND.running],
    ["-attention", BRAND.attention],
  ];
  for (const [suffix, statusColor] of faviconVariants) {
    const svg = createBrandSvg({
      pathData: mark.pathData,
      markScale: BRAND.tileMarkScale,
      tile: true,
      statusColor,
      pixelSize: 48,
    });
    const png = await renderPng(svg, 48);
    for (const scheme of ["dark", "light"]) {
      outputs.set(`packages/app/assets/images/favicon-${scheme}${suffix}.svg`, svg);
      outputs.set(`packages/app/assets/images/favicon-${scheme}${suffix}.png`, png);
    }
  }

  const desktopSizes = [16, 32, 48, 64, 128, 256, 512, 1024];
  const desktopPngBySize = new Map();
  for (const size of desktopSizes) {
    desktopPngBySize.set(size, await renderPng(tileSvg, size));
  }
  outputs.set("packages/desktop/assets/32x32.png", desktopPngBySize.get(32));
  outputs.set("packages/desktop/assets/64x64.png", desktopPngBySize.get(64));
  outputs.set("packages/desktop/assets/128x128.png", desktopPngBySize.get(128));
  outputs.set("packages/desktop/assets/128x128@2x.png", desktopPngBySize.get(256));
  outputs.set("packages/desktop/assets/icon.png", desktopPngBySize.get(512));
  outputs.set(
    "packages/desktop/assets/icon.ico",
    createIco(
      [16, 32, 48, 64, 128, 256].map((size) => ({
        size,
        data: desktopPngBySize.get(size),
      })),
    ),
  );
  outputs.set("packages/desktop/assets/icon.icns", createIcns(desktopPngBySize));

  const manifest = {
    schemaVersion: 1,
    source: SOURCE_RELATIVE_PATH,
    sourceSha256: sha256(source),
    brand: BRAND,
    generated: Object.fromEntries(
      [...outputs.entries()]
        .sort(([left], [right]) => left.localeCompare(right))
        .map(([relativePath, content]) => [relativePath, sha256(content)]),
    ),
  };
  outputs.set(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);
  return outputs;
}

async function writeOutputs(outputs) {
  for (const [relativePath, content] of outputs) {
    const absolutePath = path.join(REPO_ROOT, relativePath);
    await mkdir(path.dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, content);
  }
}

async function checkOutputs(outputs) {
  const stale = [];
  for (const [relativePath, expected] of outputs) {
    const absolutePath = path.join(REPO_ROOT, relativePath);
    let actual;
    try {
      actual = await readFile(absolutePath);
    } catch {
      stale.push(`${relativePath} (missing)`);
      continue;
    }
    const expectedBuffer = Buffer.isBuffer(expected) ? expected : Buffer.from(expected);
    if (!actual.equals(expectedBuffer)) stale.push(relativePath);
  }
  if (stale.length > 0) {
    throw new Error(
      `Daseo brand assets are stale:\n${stale.map((entry) => `- ${entry}`).join("\n")}\nRun npm run brand:generate.`,
    );
  }
}

export async function generateDaseoBrandAssets({ check = false } = {}) {
  const outputs = await buildBrandOutputs();
  if (check) await checkOutputs(outputs);
  else await writeOutputs(outputs);
  return outputs;
}

const isMain = process.argv[1]
  ? import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
  : false;
if (isMain) {
  await generateDaseoBrandAssets({ check: process.argv.includes("--check") });
  console.log(
    process.argv.includes("--check")
      ? "Daseo brand assets are current."
      : "Generated Daseo brand assets.",
  );
}
